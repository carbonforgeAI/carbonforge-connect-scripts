"""Generate the masking identifiers of the Terraform module and the CloudFormation template.

aws/identifiers.json is the single source of the CloudWatch masking identifiers. This script
writes aws/terraform/identifiers.tf, and the masking policy block between the generated-block
markers of aws/cloudformation/connect.yaml. CI runs it with --check so they cannot drift apart.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = REPO / "aws" / "identifiers.json"
TF_TARGET = REPO / "aws" / "terraform" / "identifiers.tf"
CFN_TARGET = REPO / "aws" / "cloudformation" / "connect.yaml"

# AWS rejects a data protection policy with more custom identifiers than this.
MAX_CUSTOM = 10
CUSTOM_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")

HEADER = """\
# Generated from aws/identifiers.json by scripts/gen_identifiers.py. Do not edit by hand:
# change the JSON and run the script. The list must stay identical to AWS step 2 of the setup
# runbook (cloud_setup.md), so the manual steps and this module mask the same way.
"""


def hcl_string(value: str) -> str:
    """Quote a string for HCL so Terraform reads back exactly the same characters."""
    # JSON escaping matches HCL's for quotes, backslashes and control characters; HCL also
    # treats ${ and %{ as templates, which doubling the first character turns into literals.
    return json.dumps(value).replace("${", "$${").replace("%{", "%%{")


def validated(identifiers: dict[str, object]) -> tuple[list[str], dict[str, str]]:
    """Return the managed names and the custom name-to-regex map, checked.

    Raises ValueError if the input is not a list of managed names and a name-to-regex object,
    if there are more custom identifiers than AWS allows, or if a custom name cannot be an
    unquoted HCL key.
    """
    managed = identifiers.get("managed")
    custom = identifiers.get("custom")
    if not (
        isinstance(managed, list)
        and all(isinstance(name, str) for name in managed)
        and isinstance(custom, dict)
        and all(isinstance(regex, str) for regex in custom.values())
    ):
        raise ValueError('identifiers must be {"managed": [names], "custom": {name: regex}}')
    if len(custom) > MAX_CUSTOM:
        raise ValueError(
            f"AWS allows at most {MAX_CUSTOM} custom data identifiers, got {len(custom)}"
        )
    for name in custom:
        if not CUSTOM_NAME.match(name):
            raise ValueError(f"custom identifier name {name!r} must match {CUSTOM_NAME.pattern}")
    return managed, custom


def render(identifiers: dict[str, object]) -> str:
    """Return the content of identifiers.tf for the given identifiers, in source order.

    Raises ValueError as validated() does.
    """
    managed, custom = validated(identifiers)
    width = max((len(name) for name in custom), default=0)
    lines = ["locals {", "  managed_data_identifiers = ["]
    lines += [f"    {hcl_string(name)}," for name in managed]
    lines += [
        "  ]",
        "",
        f"  # AWS allows at most {MAX_CUSTOM} custom data identifiers per policy.",
        "  custom_data_identifiers = {",
    ]
    lines += [f"    {name.ljust(width)} = {hcl_string(regex)}" for name, regex in custom.items()]
    lines += ["  }", "}"]
    return HEADER + "\n" + "\n".join(lines) + "\n"


CFN_BEGIN = "      # BEGIN generated by scripts/gen_identifiers.py from aws/identifiers.json"
CFN_END = "      # END generated"


def yaml_string(value: str) -> str:
    """Quote a string for YAML: single-quoted scalars keep backslashes as they are."""
    return "'" + value.replace("'", "''") + "'"


def render_cfn(identifiers: dict[str, object]) -> str:
    """Return the masking policy block of connect.yaml (the log group's DataProtectionPolicy).

    It is the policy the Terraform module builds. Raises ValueError as validated() does.
    """
    managed, custom = validated(identifiers)
    ids = [f"arn:aws:dataprotection::aws:data-identifier/{name}" for name in managed]
    ids += list(custom)
    id_lines = [f"              - {yaml_string(i)}" for i in ids]
    lines = [
        "      DataProtectionPolicy:",
        "        Name: carbonforge-mask-pii",
        "        Version: '2021-06-01'",
        "        Configuration:",
        "          CustomDataIdentifier:",
    ]
    for name, regex in custom.items():
        lines += [
            f"            - Name: {yaml_string(name)}",
            f"              Regex: {yaml_string(regex)}",
        ]
    lines += ["        Statement:", "          - Sid: audit", "            DataIdentifier:"]
    lines += id_lines
    lines += [
        "            Operation:",
        "              Audit:",
        "                FindingsDestination:",
        "                  CloudWatchLogs:",
        "                    LogGroup: !Ref FindingsLogGroup",
        "          - Sid: mask",
        "            DataIdentifier:",
    ]
    lines += id_lines
    lines += [
        "            Operation:",
        "              Deidentify:",
        "                MaskConfig: {}",
    ]
    return "\n".join(lines) + "\n"


def splice_cfn(template: str, block: str) -> str:
    """Return the template with the text between its generated-block markers replaced.

    Raises ValueError unless the template has exactly one begin marker followed by one end marker.
    """
    lines = template.splitlines(keepends=True)
    begins = [i for i, line in enumerate(lines) if line.rstrip("\n") == CFN_BEGIN]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == CFN_END]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ValueError(f"expected one pair of generated-block markers ({CFN_BEGIN.strip()!r})")
    return "".join(lines[: begins[0] + 1]) + block + "".join(lines[ends[0] :])


def read(path: Path) -> str | None:
    """Return a file's text, or None if it does not exist."""
    return path.read_text(encoding="utf-8") if path.exists() else None


def main(argv: list[str] | None = None) -> int:
    """Write both generated files, or with --check report whether they are up to date.

    Returns 1 if --check finds a file out of date, or if the template has lost its markers.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a file is out of date")
    parser.add_argument("--source", type=Path, default=SOURCE, help="identifiers JSON")
    parser.add_argument("--tf-target", type=Path, default=TF_TARGET, help="identifiers.tf")
    parser.add_argument("--cfn-target", type=Path, default=CFN_TARGET, help="connect.yaml")
    args = parser.parse_args(argv)

    identifiers = json.loads(args.source.read_text(encoding="utf-8"))
    try:
        cfn = splice_cfn(read(args.cfn_target) or "", render_cfn(identifiers))
    except ValueError as error:
        print(f"{args.cfn_target}: {error}", file=sys.stderr)
        return 1
    wanted = {args.tf_target: render(identifiers), args.cfn_target: cfn}

    if not args.check:
        for path, text in wanted.items():
            path.write_text(text, encoding="utf-8")
        return 0
    stale = [path for path, text in wanted.items() if read(path) != text]
    for path in stale:
        print(
            f"{path} is out of date with {args.source}: run scripts/gen_identifiers.py",
            file=sys.stderr,
        )
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
